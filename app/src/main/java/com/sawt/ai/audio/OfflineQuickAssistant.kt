package com.sawt.ai.audio

import java.text.Normalizer

/**
 * Small offline help assistant for common SAWT AI questions.
 *
 * This is deliberately a bounded, retrieval-style helper rather than an
 * on-device generative language model, so it remains light on 2 GB devices.
 */
object OfflineQuickAssistant {
    fun reply(userText: String): String {
        val text = normalize(userText)
        if (text.isBlank()) return "اكتب سؤالك وسأحاول مساعدتك."

        return when {
            text.containsAny("السلام عليكم", "مرحبا", "اهلا", "هلا", "صباح الخير", "مساء الخير") ->
                "وعليكم السلام! أهلًا بك في SAWT AI. اسألني عن تحويل النص إلى صوت أو اختيار الأصوات أو حفظ التسجيلات."

            text.containsAny("من انت", "من انت", "ماذا تستطيع", "ايش تقدر", "ما الذي تستطيع", "مساعد") ->
                "أنا المساعد المحلي الخفيف داخل SAWT AI. أجيب دون إنترنت عن أسئلة استخدام التطبيق والأصوات والتنزيل والحفظ. للأسئلة العامة وشرح النصوص الطويلة استخدم وضع Gemini المتصل."

            text.containsAny("بدون انترنت", "دون انترنت", "بدون نت", "دون نت", "اوفلاين", "offline", "الانترنت", "الاتصال") ->
                "نعم. بعد تنزيل حزمة الأصوات وتثبيتها بنجاح، يعمل تحويل النص إلى صوت دون إنترنت. المساعد المحلي يعمل دون إنترنت أيضًا. أما Gemini فيحتاج إلى اتصال ومفتاح API."

            text.containsAny("كيف استخدم", "طريقة الاستخدام", "كيف احول", "انشاء صوت", "انشئ صوت", "ابدأ", "الخطوات") ->
                "لإنشاء تسجيل: اكتب النص أو الصقه، اختر اللغة، ثم اختر الصوت الرجالي أو النسائي. اضغط «إنشاء الصوت والاستماع». بعد ظهور التسجيل يمكنك تشغيله مرة أخرى أو حفظ ملف WAV."

            text.containsAny("تحميل الاصوات", "تنزيل الاصوات", "اثبت الاصوات", "تثبيت الاصوات", "النموذج", "حزمة الاصوات") ->
                "نزّل حزمة الأصوات من الشاشة الرئيسية عبر زر «تنزيل وتجهيز الأصوات كلها». يحتاج التنزيل الأول إلى الإنترنت ومساحة فارغة كافية. لا تغلق التطبيق حتى تظهر رسالة اكتمال التثبيت."

            text.containsAny("العربي", "العربية", "فصحى", "الانجليزي", "الانجليزية", "لغات", "لغة") ->
                "يدعم محرك الصوت في المشروع العربية والإنجليزية. اختر «العربية» للنص العربي أو English للنص الإنجليزي قبل إنشاء التسجيل. للحصول على نطق أوضح، استخدم علامات الترقيم وشكّل الكلمات التي قد تحتمل أكثر من نطق."

            text.containsAny("رجالي", "رجاليه", "ذكر", "رجل", "male", "صوت رجل") ->
                "توجد اختيارات الأصوات الرجالية M1 إلى M5. اختر فئة الأصوات الرجالية ثم استمع إلى عينة الصوت قبل إنشاء التسجيل."

            text.containsAny("نسائي", "انثى", "مراه", "امرأه", "female", "صوت امراه") ->
                "توجد اختيارات الأصوات النسائية F1 إلى F5. اختر فئة الأصوات النسائية ثم استمع إلى عينة الصوت قبل إنشاء التسجيل."

            text.containsAny("احفظ", "حفظ", "تحميل الملف", "اين اجد", "مكان التسجيل", "التسجيلات", "wav") ->
                "بعد إنشاء الصوت اضغط «حفظ الصوت على الهاتف». يحفظ التطبيق التسجيل بصيغة WAV داخل مجلد Downloads/SAWT AI."

            text.containsAny("كم حرف", "طويل", "طول النص", "حد النص", "مقال", "فقرة") ->
                "الحد الحالي للنص في العملية الواحدة هو 2000 حرف. للنصوص الطويلة، قسّمها إلى فقرات قصيرة؛ هذا يساعد على تقليل استهلاك الذاكرة وتسهيل إنشاء الصوت."

            text.containsAny("بطيء", "السرعه", "سرعة", "وقت التحويل", "يتاخر", "يتأخر") ->
                "سرعة التوليد تعتمد على معالج الهاتف وطول النص وجودة التوليد المختارة. جرّب وضع «سريع» ونصًا أقصر، وأغلق التطبيقات الأخرى. لا يمكنني ضمان زمن ثابت على كل الأجهزة."

            text.containsAny("الصوت لا يعمل", "ما اسمع", "لا اسمع", "لا يوجد صوت", "مشكله الصوت", "مشكلة الصوت", "خطا", "خطأ", "تعطل") ->
                "جرّب رفع مستوى صوت الوسائط، والتأكد من عدم اتصال الهاتف بسماعة أخرى. إن ظهرت رسالة خطأ، أعد تشغيل التطبيق وتحقق من تثبيت حزمة الأصوات بالكامل. أرسل نص رسالة الخطأ لأساعدك في تحديد السبب."

            text.containsAny("elevenlabs", "eleven labs", "الفين لابس") ->
                "محرك الصوت المحلي في هذا المشروع هو Supertonic 3، وليس محرك ElevenLabs. يدعم العربية والإنجليزية ويعمل دون إنترنت، لكن لا أستطيع الادعاء أن جودة صوته مطابقة لـ ElevenLabs؛ فالتطابق يحتاج اختبارًا صوتيًا ومقارنة فعلية."

            text.containsAny("اشرح النص", "لخص", "لخص النص", "ترجم", "حلل النص", "سؤال عام") ->
                "هذا الوضع المحلي مخصص لإرشادات SAWT AI والأسئلة الشائعة، وليس نموذجًا لغويًا عامًا. لشرح نص حر أو تلخيصه أو ترجمته، بدّل إلى Gemini المتصل؛ يحتاج إنترنت ومفتاحك الشخصي."

            else ->
                "لم أجد جوابًا موثوقًا لهذا السؤال في دليل SAWT AI المحلي. أستطيع المساعدة دون إنترنت في إعداد الأصوات والتنزيل والتحويل والحفظ. للأسئلة العامة أو شرح نص ترجم إلى وضع Gemini المتصل."
        }
    }

    private fun normalize(value: String): String =
        Normalizer.normalize(value.lowercase(), Normalizer.Form.NFD)
            .replace("\\p{Mn}+".toRegex(), "")
            .replace("[أإآٱ]".toRegex(), "ا")
            .replace("ى".toRegex(), "ي")
            .replace("ة".toRegex(), "ه")
            .replace("[^\\p{L}\\p{N}\\s]".toRegex(), " ")
            .replace("\\s+".toRegex(), " ")
            .trim()

    private fun String.containsAny(vararg terms: String): Boolean =
        terms.any { contains(normalize(it)) }
}
